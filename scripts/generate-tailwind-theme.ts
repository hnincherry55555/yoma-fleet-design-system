function titleCase(s: string): string {
  return s
    .split(/[-_\s]+/)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(" ");
}

const colorFamilyMap = new Map<
  string,
  { shade: string; cssVar: string; twClass: string; hex: string }[]
>();

if (colorCollection) {
  for (const v of colorCollection.variables) {
    const hex = resolveValue(v, colorCollection.defaultModeId);
    if (hex === null) continue;
    const [family, ...rest] = v.name.split("/");
    const slug = slugify(v.name);
    if (!colorFamilyMap.has(family)) colorFamilyMap.set(family, []);
    colorFamilyMap.get(family)!.push({
      shade: rest.join("/") || family,
      cssVar: `--color-${slug}`,
      twClass: `bg-${slug}`,
      hex: String(hex),
    });
  }
}

const colorFamilies = Array.from(colorFamilyMap, ([name, colors]) => ({
  name,
  colors,
}));

const themeGroupMap = new Map<
  string,
  {
    name: string;
    cssVar: string;
    twClass: string;
    light: string;
    dark: string;
  }[]
>();

if (themeCollection) {
  const lightModeId = themeCollection.modes.find(
    (m) => m.name === "Light",
  )?.modeId;
  const darkModeId = themeCollection.modes.find(
    (m) => m.name === "Dark",
  )?.modeId;

  if (lightModeId && darkModeId) {
    for (const v of themeCollection.variables) {
      const light = resolveValue(v, lightModeId);
      const dark = resolveValue(v, darkModeId);
      if (light === null || dark === null) continue;

      const group = v.name.split("/")[0];
      const groupSlug = slugify(group);
      const slug = slugify(v.name);
      const short = slug.startsWith(`${groupSlug}-`)
        ? slug.slice(groupSlug.length + 1)
        : slug;

      const key = titleCase(group);
      if (!themeGroupMap.has(key)) themeGroupMap.set(key, []);
      themeGroupMap.get(key)!.push({
        name: short,
        cssVar: `--theme-${slug}`,
        twClass: `bg-${slug}`,
        light: String(light),
        dark: String(dark),
      });
    }
  }
}

const themeGroups = Array.from(themeGroupMap, ([groupName, tokens]) => ({
  groupName,
  tokens,
}));

const spacings = (spacingCollection?.variables ?? []).flatMap((v) => {
  const val = resolveValue(v, spacingCollection!.defaultModeId);
  if (val === null) return [];
  const slug = slugify(v.name);
  return [
    {
      name: v.name,
      value: `${val}px`,
      cssVar: `--spacing-${slug}`,
      twClass: `p-${slug}`,
    },
  ];
});

const radii = (radiusCollection?.variables ?? []).flatMap((v) => {
  const val = resolveValue(v, radiusCollection!.defaultModeId);
  if (val === null) return [];
  const slug = radiusSlug(v.name);
  return [
    {
      name: slug,
      value: `${val}px`,
      cssVar: `--radius-${slug}`,
      twClass: `rounded-${slug}`,
    },
  ];
});

const breakpointsOut = (breakpointCollection?.variables ?? []).flatMap((v) => {
  const val = resolveValue(v, breakpointCollection!.defaultModeId);
  if (val === null) return [];
  return [
    {
      name: v.name,
      value: `${val}px`,
      cssVar: `--breakpoint-${v.name}`,
      prefix: `${v.name}:`,
    },
  ];
});

