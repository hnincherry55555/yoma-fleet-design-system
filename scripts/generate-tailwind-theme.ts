const colorCollection = data.collections.find((c) => c.name === "Color");
const spacingCollection = data.collections.find((c) => c.name === "Spacing");
const radiusCollection = data.collections.find(
  (c) => c.name === "Shape/Radius",
);
const breakpointCollection = data.collections.find(
  (c) => c.name === "Breakpoint",
);
const themeCollection = data.collections.find((c) => c.name === "Theme");

const themeLines: string[] = [];

themeLines.push("  /* ═══ Primitive colors ═══ */");
if (colorCollection) {
  for (const v of colorCollection.variables) {
    const slug = slugify(v.name);
    themeLines.push(`  --color-${slug}: var(--color-${slug});`);
  }
}

themeLines.push("");
themeLines.push("  /* ═══ Semantic colors (switch with .dark) ═══ */");
if (themeCollection) {
  for (const v of themeCollection.variables) {
    const slug = slugify(v.name);
    themeLines.push(`  --color-${slug}: var(--theme-${slug});`);
  }
}

themeLines.push("");
themeLines.push("  /* ═══ Spacing ═══ */");
if (spacingCollection) {
  for (const v of spacingCollection.variables) {
    const slug = slugify(v.name);
    themeLines.push(`  --spacing-${slug}: var(--spacing-${slug});`);
  }
}

themeLines.push("");
themeLines.push("  /* ═══ Border Radius ═══ */");
if (radiusCollection) {
  for (const v of radiusCollection.variables) {
    const slug = radiusSlug(v.name);
    themeLines.push(`  --radius-${slug}: var(--radius-${slug});`);
  }
}

themeLines.push("");
themeLines.push("  /* ═══ Breakpoints ═══ */");
if (breakpointCollection) {
  for (const v of breakpointCollection.variables) {
    const val = resolveValue(v, breakpointCollection.defaultModeId);
    if (val !== null) {
      themeLines.push(`  --breakpoint-${v.name}: ${val}px;`);
    }
  }
}

const themeCss = `/* AUTO-GENERATED by scripts/generate-tailwind-theme.ts */
/* Tailwind v4 @theme registration of Figma design tokens */
/* DO NOT EDIT MANUALLY. Re-run: npm run sync-tokens */

@theme inline {
${themeLines.join("\n")}
}
`;

