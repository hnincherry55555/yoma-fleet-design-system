import * as fs from "fs";
import * as path from "path";

interface ColorValue {
  r: number;
  g: number;
  b: number;
  a: number;
}

interface VariableAlias {
  type: "VARIABLE_ALIAS";
  id: string;
}

type ModeValue = ColorValue | VariableAlias | number;

interface Variable {
  id: string;
  name: string;
  resolvedType: "COLOR" | "FLOAT";
  valuesByMode: Record<string, ModeValue>;
  variableCollectionId: string;
}

interface Mode {
  name: string;
  modeId: string;
}

interface Collection {
  id: string;
  name: string;
  defaultModeId: string;
  modes: Mode[];
  variables: Variable[];
}

interface TokenFile {
  collections: Collection[];
}

function rgbaToHex(c: ColorValue): string {
  const r = Math.round(c.r * 255);
  const g = Math.round(c.g * 255);
  const b = Math.round(c.b * 255);
  if (c.a !== undefined && c.a < 1) {
    const a = Math.round(c.a * 255);
    return `#${r.toString(16).padStart(2, "0")}${g.toString(16).padStart(2, "0")}${b.toString(16).padStart(2, "0")}${a.toString(16).padStart(2, "0")}`;
  }
  return `#${r.toString(16).padStart(2, "0")}${g.toString(16).padStart(2, "0")}${b.toString(16).padStart(2, "0")}`;
}

function slugify(name: string): string {
  return name
    .toLowerCase()
    .replace(/\//g, "-")
    .replace(/\s+/g, "-")
    .replace(/_/g, "-")
    .replace(/--+/g, "-");
}

function radiusSlug(name: string): string {
  return name.replace(/^border-radius-/, "").toLowerCase();
}

const tokensPath = path.resolve(__dirname, "../src/design/tokens.json");
const data: TokenFile = JSON.parse(fs.readFileSync(tokensPath, "utf-8"));

const variableMap = new Map<string, Variable>();
const collectionMap = new Map<string, Collection>();

for (const collection of data.collections) {
  collectionMap.set(collection.id, collection);
  for (const variable of collection.variables) {
    variableMap.set(variable.id, variable);
  }
}

function resolveValue(
  variable: Variable,
  modeId: string,
): string | number | null {
  const value = variable.valuesByMode[modeId];
  if (value === undefined || value === null) return null;

  if (
    typeof value === "object" &&
    "type" in value &&
    value.type === "VARIABLE_ALIAS"
  ) {
    const referenced = variableMap.get(value.id);
    if (!referenced) return null;
    const refCollection = collectionMap.get(referenced.variableCollectionId);
    if (!refCollection) return null;
    return resolveValue(referenced, refCollection.defaultModeId);
  }

  if (variable.resolvedType === "COLOR") {
    return rgbaToHex(value as ColorValue);
  }

  return value as number;
}

