// 1. tokens.css: raw CSS custom properties
// ──────────────────────────────────────────────

const primitiveVars: string[] = [];
const lightVars: string[] = [];
const darkVars: string[] = [];

for (const collection of data.collections) {
  if (collection.name === "Theme") {
    const lightModeId = collection.modes.find(
      (m) => m.name === "Light",
    )?.modeId;
    const darkModeId = collection.modes.find(
      (m) => m.name === "Dark",
    )?.modeId;
    if (!lightModeId || !darkModeId) continue;

    for (const variable of collection.variables) {
      const slug = slugify(variable.name);
      const lightVal = resolveValue(variable, lightModeId);
      const darkVal = resolveValue(variable, darkModeId);
      if (lightVal !== null)
        lightVars.push(`  --theme-${slug}: ${lightVal};`);
      if (darkVal !== null) darkVars.push(`  --theme-${slug}: ${darkVal};`);
    }
  } else if (collection.name !== "Breakpoint") {
    const modeId = collection.defaultModeId;

    for (const variable of collection.variables) {
      const val = resolveValue(variable, modeId);
      if (val === null) continue;

      let varName: string;
      if (collection.name === "Shape/Radius") {
        varName = `radius-${radiusSlug(variable.name)}`;
      } else {
        const prefix = slugify(collection.name);
        varName = `${prefix}-${slugify(variable.name)}`;
      }

      const cssVal = typeof val === "number" ? `${val}px` : val;
      primitiveVars.push(`  --${varName}: ${cssVal};`);
    }
  }
}

const tokensCss = `/* AUTO-GENERATED by scripts/generate-tailwind-theme.ts */
/* Source: src/design/tokens.json (exported from Figma Variable Visualizer) */
/* DO NOT EDIT MANUALLY. Re-run: npm run sync-tokens */

@layer base {
  :root {
    /* ═══ Primitive tokens ═══ */
${primitiveVars.join("\n")}

    /* ═══ Semantic tokens (Light mode, default) ═══ */
${lightVars.join("\n")}
  }

  .dark,
  [data-theme="dark"] {
    /* ═══ Semantic tokens (Dark mode) ═══ */
${darkVars.join("\n")}
  }
}
`;

